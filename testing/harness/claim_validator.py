#!/usr/bin/env python3
"""Claim validator — PROTECTED (human-owned, do not modify via agent PR).

Validates claims in claims/pending/ against:
  - claims/schema.json (JSON Schema)
  - testing/specs/claim_contract.yaml (claim type rules)
  - testing/specs/evidence_rubric.yaml (strength/type consistency)
  - testing/specs/edge_constraints.yaml (predicate + CURIE checks, post-grounding)

Agents write claims; this validator checks them. The validator is not modifiable
by agents without a PR reviewed and approved by @gwaybio.
"""
import json
import re
import sys
from pathlib import Path

try:
    import jsonschema
    import yaml
except ImportError:
    print("ERROR: Run: pip install jsonschema pyyaml")
    sys.exit(1)

REPO_ROOT = Path(__file__).parent.parent.parent
SCHEMA_PATH = REPO_ROOT / "claims" / "schema.json"
CONTRACT_PATH = REPO_ROOT / "testing" / "specs" / "claim_contract.yaml"
RUBRIC_PATH = REPO_ROOT / "testing" / "specs" / "evidence_rubric.yaml"
EDGE_CONSTRAINTS_PATH = REPO_ROOT / "testing" / "specs" / "edge_constraints.yaml"
PENDING_DIR  = REPO_ROOT / "claims" / "pending"
ACCEPTED_DIR = REPO_ROOT / "claims" / "accepted"
REJECTED_DIR = REPO_ROOT / "claims" / "rejected"

# CURIE format: PREFIX:identifier — no pipes, no whitespace.
# Valid:   NCBIGene:4763  UniProtKB:P21359  MONDO:0009981  HP:0000957
# Invalid: NCBIGene:4974|NCBIGene:5921   (pipe-delimited multi-CURIE)
#          HGNC:7765 (space in identifier)
CURIE_RE = re.compile(r'^[A-Za-z][A-Za-z0-9._-]*:[^\s|]+$')


def load_specs():
    schema = json.loads(SCHEMA_PATH.read_text())
    contract = yaml.safe_load(CONTRACT_PATH.read_text())
    rubric = yaml.safe_load(RUBRIC_PATH.read_text())
    edge_constraints = yaml.safe_load(EDGE_CONSTRAINTS_PATH.read_text())
    return schema, contract, rubric, edge_constraints


def validate_json_schema(claim, schema):
    errors = []
    validator = jsonschema.Draft7Validator(schema)
    for err in validator.iter_errors(claim):
        errors.append(f"Schema: {err.message}")
    return errors


def validate_claim_contract(claim, contract):
    errors = []
    claim_type = claim.get("claim_type")
    if claim_type not in contract["claim_types"]:
        return [f"Contract: unknown claim_type '{claim_type}'"]

    rules = contract["claim_types"][claim_type]
    strength = claim.get("evidence_strength", 0)
    min_strength = rules.get("min_evidence_strength", 1)
    if strength < min_strength:
        errors.append(f"Contract: evidence_strength {strength} below minimum {min_strength} for '{claim_type}'")

    evidence_type = claim.get("evidence_type")
    allowed = rules.get("allowed_evidence_types", [])
    if evidence_type and allowed and evidence_type not in allowed:
        errors.append(f"Contract: evidence_type '{evidence_type}' not allowed for '{claim_type}'. Allowed: {allowed}")

    # ID lifecycle rules: pending claims have pending_id, accepted have claim_id
    status = claim.get("status")
    claim_id = claim.get("claim_id")
    pending_id = claim.get("pending_id")
    if status == "pending":
        if claim_id is not None:
            errors.append(
                "Contract: pending claim must not have claim_id set "
                "(C#### is assigned only on acceptance)"
            )
        if not pending_id:
            errors.append(
                "Contract: pending claim must have pending_id set "
                "(8-char hex, generated by generate_pending_id())"
            )
    elif status == "accepted":
        if not claim_id:
            errors.append("Contract: accepted claim must have claim_id (C####) set")
    elif status in ("rejected", "refuted"):
        # Accept both R#### (new system) and C#### (legacy — pre-two-stage-ID claims).
        # Legacy C#### rejected claims are left as-is per Gregory's direction; R####
        # will be used for all rejections going forward.
        if not claim_id or not re.match(r'^[CR][0-9]{4}$', str(claim_id)):
            errors.append(
                f"Contract: rejected/refuted claim must have claim_id set to "
                f"R#### (new) or C#### (legacy), got {claim_id!r}"
            )

    # Graude demands it: accepted claims must have curated_by and curation_date
    if claim.get("status") == "accepted":
        if claim.get("curated_by") not in ("rey", "human"):
            errors.append("Contract: status='accepted' requires curated_by='rey' or 'human'")
        if not claim.get("curation_date"):
            errors.append("Contract: status='accepted' requires curation_date to be set")

    # Rejected/refuted claims must carry a rejection_class so the routing
    # decision (structural→Otto, biological→Kim/graph) is unambiguous.
    if claim.get("status") in ("rejected", "refuted"):
        rc = claim.get("rejection_class")
        if rc not in ("structural", "biological"):
            errors.append(
                f"Contract: status='{claim['status']}' requires rejection_class "
                f"to be 'structural' or 'biological', got {rc!r}"
            )

    return errors


def validate_rubric(claim, rubric):
    errors = []
    strength = claim.get("evidence_strength")
    evidence_type = claim.get("evidence_type")
    if strength is None or evidence_type is None:
        return errors
    for rule in rubric.get("consistency_rules", []):
        if rule["evidence_strength"] == strength:
            if evidence_type in rule.get("forbidden_evidence_types", []):
                errors.append(f"Rubric: '{evidence_type}' inconsistent with strength {strength}")
    return errors


def validate_post_grounding(claim, edge_constraints):
    """Checks that only run when semantic_triple is present (after Otto grounds the claim).

    Three mechanical checks:
      1. subject_id / object_id must be single valid CURIEs (no pipes, no whitespace).
      2. predicate must exist in testing/specs/edge_constraints.yaml.
      3. related_nodes must not be empty when semantic_triple is populated.
    """
    errors = []
    triple = claim.get("semantic_triple")
    if not triple:
        return errors  # pre-grounding claim — skip all post-grounding checks

    # 1. CURIE format
    for field in ("subject_id", "object_id"):
        val = triple.get(field)
        if val and not CURIE_RE.match(val):
            errors.append(
                f"Grounding: {field} \"{val}\" is not a valid CURIE "
                f"(must match PREFIX:identifier — no pipes, no spaces)"
            )

    # 2. Predicate must exist in edge_constraints.yaml
    predicate = triple.get("predicate")
    allowed_predicates = set(edge_constraints.get("edge_types", {}).keys())
    if predicate and predicate not in allowed_predicates:
        errors.append(
            f"Grounding: predicate \"{predicate}\" not in edge_constraints.yaml "
            f"(allowed: {', '.join(sorted(allowed_predicates))})"
        )

    # 3. related_nodes must not be empty when semantic_triple is set
    if not claim.get("related_nodes"):
        errors.append(
            "Grounding: semantic_triple is populated but related_nodes is empty — "
            "list at least the subject and object nodes"
        )

    return errors


def validate_file(path, schema, contract, rubric, edge_constraints):
    try:
        claim = json.loads(path.read_text())
    except json.JSONDecodeError as e:
        return False, [f"JSON parse error: {e}"]
    errors = validate_json_schema(claim, schema)
    if not errors:
        errors += validate_claim_contract(claim, contract)
        errors += validate_rubric(claim, rubric)
        errors += validate_post_grounding(claim, edge_constraints)
    return len(errors) == 0, errors


def main():
    schema, contract, rubric, edge_constraints = load_specs()

    claim_files = sorted(
        list(PENDING_DIR.glob("*.json"))
        + list(ACCEPTED_DIR.glob("*.json"))
        + list(REJECTED_DIR.glob("*.json"))
    )
    claim_files = [f for f in claim_files if f.name != ".gitkeep"]

    if not claim_files:
        print("No claims to validate.")
        return 0

    passed = failed = 0
    for path in claim_files:
        ok, errors = validate_file(path, schema, contract, rubric, edge_constraints)
        if ok:
            print(f"  PASS  {path.name}")
            passed += 1
        else:
            print(f"  FAIL  {path.name}")
            for e in errors:
                print(f"        {e}")
            failed += 1
    print(f"\n{passed} passed, {failed} failed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
